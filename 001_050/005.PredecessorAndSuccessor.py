# previous and next number.

# ask the user for a number.
number = int(input("Enter a number: "))

# get the previous number.
previous = number - 1

# get the next number.
next_number = number + 1

# show the number entered.
print("The number entered is:", number)

# show the previous and next numbers.
print("The previous number of", number, "is", previous)

# show the next number.
print("The next number after", number, "is", next_number)


